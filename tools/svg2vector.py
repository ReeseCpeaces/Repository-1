"""Convert the simple flat SVG icons in art/ into Android VectorDrawable XML.

Handles path/rect/polygon/circle, fill colors (attribute or style), evenodd fill,
and group transforms of the form matrix(a,0,0,d,e,f) or translate(). Optional
crop (x, y, w, h) re-centres the viewport on part of the artwork.
"""
import re
import sys
import xml.etree.ElementTree as ET

NS = '{http://www.w3.org/2000/svg}'


def color(el, inherited):
    fill = el.get('fill')
    style = el.get('style', '')
    m = re.search(r'fill:\s*([^;]+)', style)
    if m:
        fill = m.group(1).strip()
    fill = fill or inherited
    m = re.match(r'rgb\((\d+),\s*(\d+),\s*(\d+)\)', fill or '')
    if m:
        fill = '#%02X%02X%02X' % tuple(int(v) for v in m.groups())
    return fill


def evenodd(el, inherited):
    style = el.get('style', '') + ';' + (el.get('fill-rule') or '')
    if 'evenodd' in style:
        return True
    if 'nonzero' in style:
        return False
    return inherited


def shape_path(el):
    tag = el.tag.replace(NS, '')
    if tag == 'path':
        return ' '.join(el.get('d').split())
    if tag == 'rect':
        x, y = float(el.get('x', 0)), float(el.get('y', 0))
        w, h = float(el.get('width')), float(el.get('height'))
        return 'M%g,%g h%g v%g h%g z' % (x, y, w, h, -w)
    if tag == 'polygon':
        pts = el.get('points').split()
        return 'M' + ' L'.join(pts) + ' Z'
    if tag == 'circle':
        cx, cy, r = float(el.get('cx')), float(el.get('cy')), float(el.get('r'))
        return 'M%g,%g a%g,%g 0 1,0 %g,0 a%g,%g 0 1,0 %g,0 z' % (cx - r, cy, r, r, 2 * r, r, r, -2 * r)
    return None


def group_attrs(transform):
    if not transform:
        return ''
    m = re.match(r'matrix\(([^)]*)\)', transform)
    if m:
        a, b, c, d, e, f = [float(v) for v in re.split(r'[ ,]+', m.group(1).strip())]
        return ' android:scaleX="%g" android:scaleY="%g" android:translateX="%g" android:translateY="%g"' % (a, d, e, f)
    m = re.match(r'translate\(([^)]*)\)', transform)
    if m:
        v = [float(x) for x in re.split(r'[ ,]+', m.group(1).strip())]
        return ' android:translateX="%g" android:translateY="%g"' % (v[0], v[1] if len(v) > 1 else 0)
    raise ValueError('unsupported transform ' + transform)


def walk(el, out, fill, eo, recolor, indent):
    for child in el:
        tag = child.tag.replace(NS, '')
        f = color(child, fill)
        e = evenodd(child, eo)
        if tag == 'g':
            out.append('%s<group%s>' % (indent, group_attrs(child.get('transform'))))
            walk(child, out, f, e, recolor, indent + '  ')
            out.append('%s</group>' % indent)
        else:
            d = shape_path(child)
            if d is None or (f or '').lower() == 'none':
                continue
            c = recolor.get((f or '#000000').upper(), f or '#000000')
            out.append('%s<path android:fillColor="%s"%s android:pathData="%s"/>' % (
                indent, c, ' android:fillType="evenOdd"' if e else '', d))


def convert(src, dst, size_dp, crop=None, recolor=None):
    root = ET.parse(src).getroot()
    vb = [float(v) for v in re.split(r'[ ,]+', root.get('viewBox').strip())]
    x, y, w, h = crop or vb
    out = []
    walk(root, out, color(root, None) if root.get('fill') or 'fill:' in root.get('style', '') else None,
         evenodd(root, False), {k.upper(): v for k, v in (recolor or {}).items()}, '    ')
    wdp = size_dp
    hdp = round(size_dp * h / w, 1)
    xml = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/svg2vector.py from %s -->' % src.split('/')[-1],
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="%gdp" android:height="%gdp"' % (wdp, hdp),
           '    android:viewportWidth="%g" android:viewportHeight="%g">' % (w, h),
           '  <group android:translateX="%g" android:translateY="%g">' % (-x, -y)]
    xml += out
    xml += ['  </group>', '</vector>', '']
    open(dst, 'w').write('\n'.join(xml))


if __name__ == '__main__':
    convert(*sys.argv[1:3], float(sys.argv[3]))
